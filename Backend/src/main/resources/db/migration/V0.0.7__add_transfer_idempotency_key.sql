ALTER TABLE TRANSACTION_RECEIPTS
    ADD COLUMN IF NOT EXISTS IDEMPOTENCY_KEY VARCHAR(64);

-- A client key is unique per sending wallet. NULLs (funding rows, transfers sent without a key) never collide.
CREATE UNIQUE INDEX IF NOT EXISTS UQ_TRANSACTION_RECEIPTS_FROM_IDEMPOTENCY
    ON TRANSACTION_RECEIPTS (FROM_ADDRESS, IDEMPOTENCY_KEY);

-- Lets the confirmation tracker find unconfirmed transfers quickly.
CREATE INDEX IF NOT EXISTS IX_TRANSACTION_RECEIPTS_PENDING
    ON TRANSACTION_RECEIPTS (TRANSACTION_TYPE)
    WHERE IS_SUCCESS IS NULL;
