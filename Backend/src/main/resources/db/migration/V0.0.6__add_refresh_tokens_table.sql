-- Refresh tokens are opaque random strings; only their SHA-256 hash is stored.
-- FAMILY_ID groups every token produced by rotating from one login, so that a replayed
-- (already rotated) token can revoke the whole chain.
CREATE TABLE IF NOT EXISTS REFRESH_TOKENS(
    REFRESH_TOKEN_ID        BIGINT NOT NULL,
    ACCOUNT_ID              INT NOT NULL,
    TOKEN_HASH              VARCHAR(64) NOT NULL,
    FAMILY_ID               VARCHAR(36) NOT NULL,
    CREATED_AT              TIMESTAMP NOT NULL,
    EXPIRES_AT              TIMESTAMP NOT NULL,
    REVOKED_AT              TIMESTAMP
    );
CREATE SEQUENCE IF NOT EXISTS SEQ_REFRESH_TOKENS START 100;
ALTER TABLE REFRESH_TOKENS ADD CONSTRAINT PK_REFRESH_TOKENS PRIMARY KEY (REFRESH_TOKEN_ID);
ALTER TABLE REFRESH_TOKENS ADD CONSTRAINT UQ_REFRESH_TOKENS_HASH UNIQUE (TOKEN_HASH);
ALTER TABLE REFRESH_TOKENS ADD CONSTRAINT FK_REFRESH_TOKENS_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES ACCOUNTS (ACCOUNT_ID);
CREATE INDEX IF NOT EXISTS IDX_REFRESH_TOKENS_FAMILY ON REFRESH_TOKENS (FAMILY_ID);
CREATE INDEX IF NOT EXISTS IDX_REFRESH_TOKENS_ACCOUNT ON REFRESH_TOKENS (ACCOUNT_ID);
