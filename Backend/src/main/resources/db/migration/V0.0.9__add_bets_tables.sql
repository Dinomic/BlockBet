-- The deployed BlockBet smart contract(s). A new row is added whenever the compiled contract changes
-- (CODE_HASH), so bets always point at the contract instance that holds their funds.
CREATE TABLE IF NOT EXISTS BET_CONTRACTS(
    BET_CONTRACT_ID     INT             NOT NULL,
    ADDRESS             VARCHAR(42)     NOT NULL UNIQUE,
    CODE_HASH           VARCHAR(66)     NOT NULL UNIQUE,
    DEPLOY_TX_HASH      VARCHAR(66)     NOT NULL,
    DEPLOYED_AT         TIMESTAMP       NOT NULL DEFAULT NOW()
    );
CREATE SEQUENCE IF NOT EXISTS SEQ_BET_CONTRACTS START 100;
ALTER TABLE BET_CONTRACTS ADD CONSTRAINT BET_CONTRACT_ID PRIMARY KEY (BET_CONTRACT_ID);

-- Off-chain description of a bet. The rules and the money (options, stake, close time, pool, winner)
-- live in the smart contract; CHAIN_BET_ID points at them.
CREATE TABLE IF NOT EXISTS BETS(
    BET_ID              INT             NOT NULL,
    BET_CONTRACT_ID     INT             NOT NULL,
    CHAIN_BET_ID        BIGINT          NOT NULL,
    TITLE               VARCHAR(128)    NOT NULL,
    DESCRIPTION         VARCHAR(1024),
    IMAGE_URL           VARCHAR(512),
    BOOKIE_WALLET_ID    INT             NOT NULL,
    CREATE_TX_HASH      VARCHAR(66)     NOT NULL,
    CREATED_AT          TIMESTAMP       NOT NULL DEFAULT NOW()
    );
CREATE SEQUENCE IF NOT EXISTS SEQ_BETS START 100;
ALTER TABLE BETS ADD CONSTRAINT BET_ID PRIMARY KEY (BET_ID);
ALTER TABLE BETS ADD CONSTRAINT FK_BETS_BET_CONTRACT_ID FOREIGN KEY (BET_CONTRACT_ID) REFERENCES BET_CONTRACTS (BET_CONTRACT_ID);
ALTER TABLE BETS ADD CONSTRAINT FK_BETS_BOOKIE_WALLET_ID FOREIGN KEY (BOOKIE_WALLET_ID) REFERENCES WALLETS (WALLET_ID);
ALTER TABLE BETS ADD CONSTRAINT UQ_BETS_CHAIN UNIQUE (BET_CONTRACT_ID, CHAIN_BET_ID);

-- Which account bet on which bet. The contract only limits one bet per wallet address; this keeps it to one per
-- account, so a bettor cannot bet again from a second wallet.
CREATE TABLE IF NOT EXISTS BET_PARTICIPANTS(
    BET_PARTICIPANT_ID  INT             NOT NULL,
    BET_ID              INT             NOT NULL,
    ACCOUNT_ID          INT             NOT NULL,
    WALLET_ADDRESS      VARCHAR(42)     NOT NULL,
    BET_OPTION          VARCHAR(1)      NOT NULL,
    TX_HASH             VARCHAR(66)     NOT NULL,
    CREATED_AT          TIMESTAMP       NOT NULL DEFAULT NOW()
    );
CREATE SEQUENCE IF NOT EXISTS SEQ_BET_PARTICIPANTS START 100;
ALTER TABLE BET_PARTICIPANTS ADD CONSTRAINT BET_PARTICIPANT_ID PRIMARY KEY (BET_PARTICIPANT_ID);
ALTER TABLE BET_PARTICIPANTS ADD CONSTRAINT FK_BET_PARTICIPANTS_BET_ID FOREIGN KEY (BET_ID) REFERENCES BETS (BET_ID);
ALTER TABLE BET_PARTICIPANTS ADD CONSTRAINT FK_BET_PARTICIPANTS_ACCOUNT_ID FOREIGN KEY (ACCOUNT_ID) REFERENCES ACCOUNTS (ACCOUNT_ID);
ALTER TABLE BET_PARTICIPANTS ADD CONSTRAINT UQ_BET_PARTICIPANTS UNIQUE (BET_ID, ACCOUNT_ID);
